#!/usr/bin/env node
/**
 * script-dictionary.mjs — Script Dictionary / Scriptionary Builder
 * Scans scripts/factory and builds scriptionary.json from @forge-* metadata.
 * Run after any script change to keep the dictionary current.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const THIS_FILE = fileURLToPath(import.meta.url);
const SCRIPT_DIR = dirname(THIS_FILE);
const DIC_PATH = join(SCRIPT_DIR, "scriptionary.json");

const FORGE_TYPES = {
  gate:"Gate — approves/redirects before execution",
  forge:"Forge — bounded conversion unit",
  orchestrator:"Orchestrator — coordinates multiple forges",
  station:"Station — workflow stopping point",
  artifact:"Artifact — produces durable file/map/record",
  sensor:"Sensor — observes without mutating",
  watchdog:"Watchdog — monitors conditions, triggers alerts",
  bridge:"Bridge — moves data between systems",
  trigger:"Trigger — fires on schedule or event",
  dataset:"Dataset — structured data storage/query",
};

const OPERATING_MODES = {
  DISCUSS:"Free-form AI chat — bypasses scripts, no gate",
  MICRO:"≤1 file mutation — fires directly, no gate",
  BUILD:"Full scope — requires satisfaction contract",
  PLAN:"Novel/complex — routed to plan first",
};

function parseForgeMeta(relPath, code) {
  const name = relPath.split("/").pop().replace(/\.mjs$/, "");
  const m = {};
  const idM = code.match(/@forge-id\s+(\S+)/); if(idM) m.id = idM[1];
  const nmM = code.match(/@forge-name\s+(.+)/); if(nmM) m.name = nmM[1].trim();
  const tyM = code.match(/@forge-type\s+(\S+)/); if(tyM) m.type = tyM[1];
  m.triggers = (code.match(/@trigger\s+(.+)/g)||[]).map(t=>t.replace(/@trigger\s+/,"").trim());
  const dM = code.match(/@description\s+(.+)/); if(dM) m.description = dM[1].trim();
  m.opcodes = (code.match(/@opcode\s+(\S+)/g)||[]).map(o=>o.replace(/@opcode\s+/,""));
  m.guards = (code.match(/@guard\s+(.+)/g)||[]).map(g=>g.replace(/@guard\s+/,"").trim());
  const stM = code.match(/@status\s+(\S+)/); if(stM) m.status = stM[1];
  const vM = code.match(/@version\s+(\S+)/); if(vM) m.version = vM[1];
  if(!m.name) m.name = name.replace(/-/g," ").replace(/\b\w/g,c=>c.toUpperCase());
  return m;
}

function scanDir(dir) {
  const results = [];
  if(!existsSync(dir)) return results;
  for(const entry of readdirSync(dir,{withFileTypes:true})) {
    const fp = join(dir,entry.name);
    if(entry.isDirectory()) results.push(...scanDir(fp));
    else if(entry.name.endsWith(".mjs")) {
      try {
        const code = readFileSync(fp,"utf8");
        const rel = fp.replace(SCRIPT_DIR+"/","");
        const meta = parseForgeMeta(rel,code);
        if(meta.id||meta.triggers.length>0||meta.description) {
          meta._file = rel;
          if(!meta.id) meta.id = entry.name.replace(/\.mjs$/,"");
          results.push(meta);
        }
      }catch{}
    }
  }
  return results;
}

const force = process.argv.includes("--force");
const fmtOnly = process.argv.includes("--fmt");
console.log("[dict] Scriptionary builder starting");console.log("[dict] SCRIPT_DIR:",SCRIPT_DIR);
const forges = scanDir(SCRIPT_DIR);console.log('[dict] dir entries:', readdirSync(SCRIPT_DIR,{withFileTypes:true}).filter(e=>e.name.endsWith('.mjs')).map(e=>e.name));
console.log(`[dict] Scanned ${forges.length} forges`);

if(fmtOnly) {
  const ex = existsSync(DIC_PATH)?JSON.parse(readFileSync(DIC_PATH,"utf8")):{};
  writeFileSync(DIC_PATH,JSON.stringify(ex,null,2));
  console.log("[dict] Formatted existing");
  process.exit(0);
}

const forgeMap = {};
for(const f of forges) {
  forgeMap[f.id] = {
    plain_english:f.name,
    meaning:f.description||FORGE_TYPES[f.type]||FORGE_TYPES.forge,
    rule:`Use ${f.id} when ${f.triggers.length?f.triggers.join(", "):"trigger conditions are met"}.`,
    triggers:f.triggers,opcodes:f.opcodes,guards:f.guards,
    type:f.type,file:f._file,status:f.status||"pending",
  };
}

let existing = {};
if(existsSync(DIC_PATH)&&!force) { try{existing=JSON.parse(readFileSync(DIC_PATH,"utf8"));}catch{} }

const updated = {
  ...existing,
  _updated:new Date().toISOString(),
  _note:"Auto-generated by script-dictionary.mjs",
  Forge:forgeMap,
  Scriptonomy:{DISCUSS:OPERATING_MODES.DISCUSS,MICRO:OPERATING_MODES.MICRO,BUILD:OPERATING_MODES.BUILD,PLAN:OPERATING_MODES.PLAN},
  BootstrapSources:{
    github:"git clone from canonical repo — default source",
    hive:"pull packages from registered Hive via /api/hive — Cell bootstrap",
    interlink:"Zo-to-Zo ask API — direct from director Zo — emergency/override",
    skill:"use refer-library-bootstrap skill — skill-based bootstrap",
  },
  HiveCellArchitecture:{
    Hive:"Distribution hub — owns manifest, receives heartbeats, dispatches work",
    Cell:"A Zo registered to a Hive — fires heartbeats, receives dispatches",
    Terminal:"A standalone Zo not connected to any Hive",
  },
};
writeFileSync(DIC_PATH,JSON.stringify(updated,null,2));
console.log(`[dict] Written: ${forges.length} forges to ${DIC_PATH}`);
console.log("\nForges:");
for(const f of forges) console.log(`  ${(f.id||"").padEnd(28)} ${(f.type||"?").padEnd(14)} ${f.triggers.join(", ")||"(no triggers)"}`);
